'use strict';
// A small .xlsx writer: sheets of cells (values or formulas), a few number styles, column widths.
// Excel recalculates every formula when the file opens (fullCalcOnLoad), so formulas need no cached values.
const zlib = require('node:zlib');

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
  .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');
const colName = n => { let s = ''; while (n > 0) { const m = (n - 1) % 26; s = String.fromCharCode(65 + m) + s; n = Math.floor((n - 1) / 26); } return s; };

// style ids (cellXfs order below)
const STYLE = { text: 0, bold: 1, money: 2, moneyBold: 3, num: 4, pct: 5, title: 6, head: 7, hours: 8, section: 9, wrap: 10 };

function zip(files) {
  const parts = [], dir = []; let off = 0;
  for (const [name, text] of files) {
    const data = Buffer.isBuffer(text) ? text : Buffer.from(text, 'utf8'), nm = Buffer.from(name), crc = zlib.crc32(data), comp = zlib.deflateRawSync(data);
    const h = Buffer.alloc(30); h.writeUInt32LE(0x04034b50, 0); h.writeUInt16LE(20, 4); h.writeUInt16LE(8, 8);
    h.writeUInt32LE(crc, 14); h.writeUInt32LE(comp.length, 18); h.writeUInt32LE(data.length, 22); h.writeUInt16LE(nm.length, 26);
    parts.push(h, nm, comp);
    const c = Buffer.alloc(46); c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(20, 4); c.writeUInt16LE(20, 6); c.writeUInt16LE(8, 10);
    c.writeUInt32LE(crc, 16); c.writeUInt32LE(comp.length, 20); c.writeUInt32LE(data.length, 24); c.writeUInt16LE(nm.length, 28); c.writeUInt32LE(off, 42);
    dir.push(c, nm);
    off += 30 + nm.length + comp.length;
  }
  const cd = Buffer.concat(dir), e = Buffer.alloc(22);
  e.writeUInt32LE(0x06054b50, 0); e.writeUInt16LE(files.length, 8); e.writeUInt16LE(files.length, 10); e.writeUInt32LE(cd.length, 12); e.writeUInt32LE(off, 16);
  return Buffer.concat([...parts, cd, e]);
}

